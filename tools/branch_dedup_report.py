#!/usr/bin/env python3
"""Read-only triage report for unmerged local ``refs/heads/agent/*`` branches.

For every local agent ref that is not an ancestor of HEAD (checked with
``git merge-base --is-ancestor``), this tool runs
``git rev-list --left-right --count HEAD...<branch>`` and groups the result:

* Band A - 0 behind / 1 ahead: a single commit on top of HEAD (safe candidate).
* Band B - nonzero behind / 1 ahead: one commit, but HEAD has moved on (rebase).
* Band C - any other unmerged shape: divergent, older lineage.

Only read-only git commands are used (rev-parse, for-each-ref, merge-base,
rev-list). There is no fetch, checkout, merge, ref update, or worktree write.
``GIT_OPTIONAL_LOCKS=0`` keeps git from taking optional index/ref locks.

Usage::

    python3 tools/branch_dedup_report.py --repo /path/to/repo
    python3 tools/branch_dedup_report.py --repo /path/to/repo --limit 40
"""
from __future__ import annotations

import argparse
import os
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable, Sequence

DEFAULT_PREFIX = "refs/heads/agent/"
DEFAULT_LIMIT = 40

BAND_SAFE = "A"
BAND_REBASE = "B"
BAND_DIVERGED = "C"
BANDS = (BAND_SAFE, BAND_REBASE, BAND_DIVERGED)

BAND_TITLES = {
    BAND_SAFE: "safe single-commit candidates (0 behind / 1 ahead)",
    BAND_REBASE: "rebase needed (nonzero behind / 1 ahead)",
    BAND_DIVERGED: "divergent older lineage (all other unmerged shapes)",
}

@dataclass(frozen=True)
class BranchStat:
    """One unmerged branch and its symmetric-difference counts vs HEAD."""

    name: str  # exact full refname, e.g. refs/heads/agent/foo-r18-20261126
    behind: int  # commits reachable from HEAD but not from the branch
    ahead: int  # commits reachable from the branch but not from HEAD
    subject: str  # tip commit subject, for human context only


@dataclass
class Report:
    """Collected facts, separated from presentation so tests can inspect them."""

    repo: str
    head: str
    prefix: str
    limit: int
    enumerated: int = 0
    contained: int = 0
    unmerged: int = 0
    bands: dict[str, list[BranchStat]] = field(
        default_factory=lambda: {band: [] for band in BANDS}
    )

    def omitted(self, band: str) -> int:
        return max(0, len(self.bands[band]) - self.limit)

    def render(self) -> str:
        """Render the ranked markdown report (stdout-only; no side effects)."""
        lines = [
            "# Unmerged agent branch dedup report",
            "",
            f"- Repo: {_cell(self.repo)}",
            f"- HEAD: `{self.head}`",
            f"- Ref prefix: `{self.prefix}`",
            f"- Enumerated refs: {self.enumerated}",
            f"- Already contained in HEAD (excluded): {self.contained}",
            f"- Unmerged branches analyzed: {self.unmerged}",
            f"- Display cap per band: {self.limit}",
            "",
            (
                "Band A = 0 behind / 1 ahead (safe single commit); "
                "Band B = nonzero behind / 1 ahead (rebase needed); "
                "Band C = all other unmerged shapes (divergent older lineage). "
                "Ranking: A by branch name; B by fewest behind then name; "
                "C by fewest ahead, then fewest behind, then name."
            ),
            "",
        ]
        for band in BANDS:
            rows = self.bands[band]
            shown = rows[: self.limit]
            lines.append(
                f"## Band {band} - {BAND_TITLES[band]} "
                f"({len(rows)} total, showing {len(shown)})"
            )
            lines.append("")
            if not rows:
                lines.append("_None._")
            else:
                lines.append("| # | Branch | Behind | Ahead | Tip subject |")
                lines.append("|---:|---|---:|---:|---|")
                for number, stat in enumerate(shown, 1):
                    lines.append(
                        f"| {number} | `{stat.name}` | {stat.behind} | "
                        f"{stat.ahead} | {_cell(stat.subject)} |"
                    )
                if self.omitted(band):
                    lines.append("")
                    lines.append(
                        f"_Omitted from display: {self.omitted(band)} "
                        f"(of {len(rows)}; raise --limit to see more)._"
                    )
            lines.append("")
        lines.append(
            "Generated by tools/branch_dedup_report.py "
            "(read-only: no fetch, no ref changes, no merges)."
        )
        return "\n".join(lines) + "\n"


def _cell(text: str) -> str:
    """Make a single-line, markdown-table-safe cell from untrusted git text."""
    collapsed = " ".join(text.split())
    return collapsed.replace("|", "\\|") or "(no subject)"


def _git(repo: Path, *args: str) -> subprocess.CompletedProcess[str]:
    env = os.environ.copy()
    env["GIT_OPTIONAL_LOCKS"] = "0"
    env["GIT_TERMINAL_PROMPT"] = "0"
    env["LC_ALL"] = "C"
    return subprocess.run(
        ["git", "-C", str(repo), *args],
        capture_output=True,
        text=True,
        env=env,
        check=False,
    )


def _git_checked(repo: Path, *args: str) -> str:
    result = _git(repo, *args)
    if result.returncode != 0:
        detail = result.stderr.strip() or result.stdout.strip() or "no output"
        raise RuntimeError(f"git {' '.join(args)} failed: {detail}")
    return result.stdout


def classify(behind: int, ahead: int) -> str:
    """Map symmetric-difference counts to a report band."""
    if behind == 0 and ahead == 1:
        return BAND_SAFE
    if ahead == 1:
        return BAND_REBASE
    return BAND_DIVERGED


def _sort_key(band: str) -> Callable[[BranchStat], tuple]:
    if band == BAND_SAFE:
        return lambda stat: (stat.name,)
    if band == BAND_REBASE:
        return lambda stat: (stat.behind, stat.name)
    return lambda stat: (stat.ahead, stat.behind, stat.name)


def enumerate_branches(repo: Path, prefix: str) -> list[tuple[str, str]]:
    """Return (full refname, tip subject) pairs for refs under ``prefix``."""
    out = _git_checked(
        repo, "for-each-ref", "--format=%(refname)%09%(subject)", prefix
    )
    branches: list[tuple[str, str]] = []
    seen: set[str] = set()
    for line in out.splitlines():
        if not line.strip():
            continue
        name, _, subject = line.partition("\t")
        if not name.startswith(prefix) or name in seen:
            continue
        seen.add(name)
        branches.append((name, subject))
    return branches


def collect(repo: Path, head: str, prefix: str, limit: int) -> Report:
    """Build a Report from a local git repository. Never mutates the repo."""
    if limit < 1:
        raise ValueError("limit must be >= 1")
    head_oid = _git_checked(repo, "rev-parse", "--verify", f"{head}^{{commit}}").strip()
    report = Report(
        repo=str(repo.resolve()),
        head=head_oid,
        prefix=prefix,
        limit=limit,
    )
    branches = enumerate_branches(repo, prefix)
    report.enumerated = len(branches)

    for name, subject in branches:
        ancestor = _git(repo, "merge-base", "--is-ancestor", name, head_oid)
        if ancestor.returncode == 0:
            report.contained += 1
            continue
        if ancestor.returncode != 1:
            detail = ancestor.stderr.strip() or "no output"
            raise RuntimeError(
                f"git merge-base --is-ancestor {name} HEAD failed "
                f"(rc {ancestor.returncode}): {detail}"
            )

        counts = _git_checked(
            repo, "rev-list", "--left-right", "--count", f"{head_oid}...{name}"
        ).split()
        if len(counts) != 2:
            raise RuntimeError(f"unexpected rev-list count output for {name}: {counts!r}")
        try:
            behind, ahead = int(counts[0]), int(counts[1])
        except ValueError as exc:
            raise RuntimeError(f"non-numeric rev-list counts for {name}: {counts!r}") from exc

        report.unmerged += 1
        report.bands[classify(behind, ahead)].append(
            BranchStat(name=name, behind=behind, ahead=ahead, subject=subject)
        )

    for band in BANDS:
        report.bands[band].sort(key=_sort_key(band))
    return report


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Rank unmerged local agent branches by merge readiness (read-only)."
    )
    parser.add_argument(
        "--repo", default=".", help="repository to inspect (default: current directory)"
    )
    parser.add_argument("--head", default="HEAD", help="baseline ref (default: HEAD)")
    parser.add_argument(
        "--prefix", default=DEFAULT_PREFIX, help="ref prefix to enumerate"
    )
    parser.add_argument(
        "--limit",
        type=int,
        default=DEFAULT_LIMIT,
        help=f"max rows shown per band (default: {DEFAULT_LIMIT})",
    )
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    try:
        report = collect(Path(args.repo), args.head, args.prefix, args.limit)
    except (RuntimeError, ValueError, OSError) as exc:
        print(f"branch_dedup_report: error: {exc}", file=sys.stderr)
        return 2
    sys.stdout.write(report.render())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
